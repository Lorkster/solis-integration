// Builds the browser dashboard from the widget files, so the widgets exist in one place only:
//  - homey-app/settings/: the app's settings page in Homey (logged in, also remotely)
//  - docs/dashboard/: the standalone page for a browser or wall screen on the home network
// Usage: node tools/build-dashboard.mjs
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const host = readFileSync(join(root, 'tools/dashboard/host.html'), 'utf8');
const widgets = ['battery-status', 'battery-plan'];
const note = '<!-- Generated by tools/build-dashboard.mjs from tools/dashboard/host.html. Do not edit by hand. -->\n';

const targets = [
  { dir: join(root, 'homey-app/settings'), script: '<script type="text/javascript" src="/homey.js" data-origin="settings"></script>' },
  { dir: join(root, 'docs/dashboard'), script: '' },
];
for (const { dir, script } of targets) {
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, 'index.html'), note + host.replace('<!--HOMEY_SCRIPT-->', script));
  for (const id of widgets) {
    copyFileSync(join(root, 'homey-app/widgets', id, 'public/index.html'), join(dir, `widget-${id}.html`));
  }
  console.log('Built', dir);
}
