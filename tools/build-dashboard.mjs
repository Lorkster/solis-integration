// Builds the browser dashboard from the widget files, so the widgets exist in one place only. The
// result is one self-contained HTML file (widgets built in), which also works opened from disk.
//  - homey-app/settings/index.html: the app's settings page in Homey (Homey login)
//  - docs/dashboard/solis-dashboard.html: the standalone page for a browser or wall screen at home
// Usage: node tools/build-dashboard.mjs
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const host = readFileSync(join(root, 'tools/dashboard/host.html'), 'utf8');
const widgets = Object.fromEntries(['battery-status', 'battery-plan']
  .map((id) => [id, readFileSync(join(root, 'homey-app/widgets', id, 'public/index.html'), 'utf8')]));
// JSON inside a <script>: keep "</script>" in the widget sources from ending it.
const embedded = JSON.stringify(widgets).replace(/<\/(script)/gi, '<\\/$1');
const note = '<!-- Generated by tools/build-dashboard.mjs from tools/dashboard/host.html and the widgets. Do not edit by hand. -->\n';
const page = (script) => note + host
  .replace('<!--HOMEY_SCRIPT-->', script)
  .replace('/*WIDGETS*/{}/*WIDGETS*/', () => embedded);

const targets = [
  { file: join(root, 'homey-app/settings/index.html'), script: '<script type="text/javascript" src="/homey.js" data-origin="settings"></script>' },
  { file: join(root, 'docs/dashboard/solis-dashboard.html'), script: '' },
];
for (const { file, script } of targets) {
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, page(script));
  console.log('Built', file);
}
// Earlier builds had separate widget files next to the page.
for (const old of ['homey-app/settings/widget-battery-status.html', 'homey-app/settings/widget-battery-plan.html',
  'docs/dashboard/widget-battery-status.html', 'docs/dashboard/widget-battery-plan.html', 'docs/dashboard/index.html']) {
  rmSync(join(root, old), { force: true });
}
